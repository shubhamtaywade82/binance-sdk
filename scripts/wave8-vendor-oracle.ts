/**
 * Wave 8 oracle vendorer — fetches connector-js response-interface files at a
 * pinned upstream commit and writes them under contracts/wave8-oracle/<product>/.
 *
 * This automates step 1-3 of the re-vendoring procedure in
 * contracts/wave8-oracle/README.md, so climbing the strictness ladder to a new
 * product is:
 *
 *   npm run contracts:wave8-vendor-oracle -- --product vipLoan --client vip-loan
 *   # author <product>.overrides.json (review surface — deliberate divergences)
 *   npm run contracts:wave8-strict-schemas -- --product vipLoan
 *   # wire the resource + fixtures + tests, lower the ratchet
 *
 * Only response-shape interfaces are vendored: files whose name contains
 * "response" (the OpenAPI Generator convention for response models, including
 * the *-inner.ts element interfaces). index.ts, rest-api.ts and the modules/
 * barrel files are skipped.
 *
 * Auth: unauthenticated for public data; set GITHUB_TOKEN when rate-limited.
 *
 * Run via: npm run contracts:wave8-vendor-oracle -- --product <name> --client <dir> \
 *            [--sha <commit>] [--doc <upstream-doc-url>] [--date <yyyy-mm-dd>]
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORACLE_DIR = join(ROOT, 'contracts', 'wave8-oracle');
const REPO = 'binance/binance-connector-js';
/** Same pin as the convert pilot unless a newer rung deliberately re-pins. */
const DEFAULT_SHA = '1fe304445e34d014a0e457ef0006f7c426f0203c';

const headers: Record<string, string> = { 'User-Agent': 'binance-sdk-wave8-vendor' };
if (process.env.GITHUB_TOKEN) headers.Authorization = `token ${process.env.GITHUB_TOKEN}`;

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

async function getJson(url: string): Promise<Record<string, unknown> & { tree?: Array<{ path: string; type: string; sha?: string }>; sha?: string; content?: string }> {
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status} ${await res.text()}`);
  return (await res.json()) as Record<string, unknown> & { tree?: Array<{ path: string; type: string; sha?: string }> };
}

async function subtreeSha(sha: string, child: string): Promise<string> {
  const tree = await getJson(`https://api.github.com/repos/${REPO}/git/trees/${sha}`);
  const entry = tree.tree?.find((e) => e.path === child);
  if (!entry?.sha) throw new Error(`no "${child}" under tree ${sha}`);
  return entry.sha;
}

async function main(): Promise<void> {
  const product = arg('product');
  const client = arg('client');
  if (!product || !client || product.startsWith('--') || client.startsWith('--')) {
    console.error(
      '[wave8-vendor] usage: wave8-vendor-oracle -- --product <sdkName> --client <connectorJsDir> [--sha <commit>] [--doc <url>] [--date <yyyy-mm-dd>]',
    );
    process.exit(2);
  }
  const sha = arg('sha') ?? DEFAULT_SHA;
  const doc = arg('doc') ?? `https://developers.binance.com/ (see ${client} client docs)`;
  const date = arg('date') ?? new Date().toISOString().slice(0, 10);
  const sourcePath = `clients/${client}/src/rest-api/types`;

  // Walk repo -> clients -> <client> -> src -> rest-api -> types.
  const rootTree = await getJson(`https://api.github.com/repos/${REPO}/git/trees/${sha}`);
  if (!rootTree.sha) throw new Error(`tree ${sha} has no sha`);
  const clientsSha = await subtreeSha(rootTree.sha, 'clients');
  const clientSha = await subtreeSha(clientsSha, client);
  const srcSha = await subtreeSha(clientSha, 'src');
  const restApiSha = await subtreeSha(srcSha, 'rest-api');
  const typesTree = await getJson(
    `https://api.github.com/repos/${REPO}/git/trees/${await subtreeSha(restApiSha, 'types')}`,
  );

  const files = (typesTree.tree ?? []).filter(
    (e) => e.type === 'blob' && e.path.endsWith('.ts') && e.path !== 'index.ts' && e.path !== 'rest-api.ts' && /response/.test(e.path),
  ) as Array<{ path: string; sha: string }>;
  if (files.length === 0) throw new Error(`no response interfaces found under ${sourcePath}/`);
  files.sort((a, b) => a.path.localeCompare(b.path));

  const outDir = join(ORACLE_DIR, product);
  mkdirSync(outDir, { recursive: true });

  for (const file of files) {
    const blob = await getJson(`https://api.github.com/repos/${REPO}/git/blobs/${file.sha}`);
    if (!blob.content) throw new Error(`blob ${file.sha} (${file.path}) has no content`);
    const content = Buffer.from(blob.content, 'base64').toString('utf8');
    const header = [
      '/*',
      ` * Vendored from ${REPO} @ ${sha} (${date})`,
      ` * Path: ${sourcePath}/${file.path}`,
      ' * Upstream file is auto-generated by OpenAPI Generator from Binance\'s official',
      ` * ${client} OpenAPI documents (developers.binance.com).`,
      ' * Wave 8 uses these interfaces as the strict-schema oracle. Do not hand-edit;',
      ' * re-vendor deliberately at a newer upstream commit with a new pin below.',
      ' */',
    ].join('\n');
    writeFileSync(join(outDir, file.path), `${header}\n${content}`);
  }

  const index = {
    schemaVersion: 1,
    product,
    sourceUrl: `https://github.com/${REPO}`,
    sourcePath,
    pinnedSha: sha,
    pinnedAt: date,
    upstreamDoc: doc,
    files: files.map((f) => f.path),
  };
  writeFileSync(join(ORACLE_DIR, `${product}.index.json`), `${JSON.stringify(index, null, 2)}\n`);

  console.log(`[wave8-vendor] ${product}: ${files.length} files from ${sourcePath} @ ${sha.slice(0, 12)} (${date})`);
  console.log(`  -> contracts/wave8-oracle/${product}/`);
  console.log(`  -> contracts/wave8-oracle/${product}.index.json`);
  console.log(`Next: author contracts/wave8-oracle/${product}.overrides.json, then run`);
  console.log(`  npm run contracts:wave8-strict-schemas -- --product ${product}`);
}

if (process.argv[1] && process.argv[1].endsWith('wave8-vendor-oracle.ts')) {
  main().catch((err) => {
    console.error(`[wave8-vendor] ${err instanceof Error ? err.message : err}`);
    process.exit(1);
  });
}
